#!/usr/bin/env python3
"""Embed the reviewed, explicitly unverified IR candidate catalog."""

import json
from pathlib import Path

source = Path('data/candidates.json')
output = Path('include/generated/candidates.h')
catalog = json.loads(source.read_text())
assert all(profile['status'] != 'verified_for_target' for profile in catalog['profiles'])
raw = json.dumps(catalog, separators=(',', ':')).encode()
lines = ['// Generated by scripts/candidates-to-header.py. Do not edit by hand.',
         '#pragma once', '#include <Arduino.h>',
         'static const char candidateCatalogJson[] PROGMEM =']
for offset in range(0, len(raw), 80):
    lines.append('  "' + ''.join(f'\\x{byte:02x}' for byte in raw[offset:offset+80]) + '"')
lines.append(';')
output.parent.mkdir(parents=True, exist_ok=True)
content = '\n'.join(lines) + '\n'
if not output.exists() or output.read_text() != content:
    output.write_text(content)
print(f'Embedded {len(catalog["profiles"])} IR candidates ({len(raw)} bytes)')
